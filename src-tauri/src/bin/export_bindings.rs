use folio::domain::{claim::*, expense::*, extraction::*, receipt::*, settings::*};
use folio::services::csv_export::CsvExport;
use ts_rs::TS;
fn main() -> Result<(), Box<dyn std::error::Error>> {
    let mut output = String::from("// Generated by `npm run bindings`. Do not edit.\n");
    macro_rules! emit{($($t:ty),*)=>{$(output.push_str("export ");output.push_str(&<$t>::decl());output.push('\n');)*}}
    emit!(
        ExpenseStatus,
        FieldSource,
        FieldMeta,
        Expense,
        ExpenseEdit,
        ReceiptFile,
        ReceiptContent,
        ImportOutcome,
        folio::error::AppError,
        Extraction,
        Job,
        JobLease,
        ClaimStatus,
        Claim,
        ClaimDetail,
        ExportSnapshot,
        Settings,
        AppInfo,
        CsvExport
    );
    let path =
        std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../src/bindings/generated/index.ts");
    std::fs::write(path, output)?;
    Ok(())
}
