use folio::domain::{claim::*, expense::*, extraction::*, finance::*, receipt::*, settings::*};
use folio::services::csv_export::CsvExport;
use ts_rs::TS;
fn main() -> Result<(), Box<dyn std::error::Error>> {
    let mut output = String::from("// Generated by `npm run bindings`. Do not edit.\n");
    macro_rules! emit{($($t:ty),*)=>{$(output.push_str("export ");output.push_str(&<$t>::decl());output.push('\n');)*}}
    emit!(
        ExpenseStatus,
        FieldSource,
        FieldMeta,
        Expense,
        ExpenseEdit,
        ReceiptFile,
        ReceiptContent,
        ImportOutcome,
        folio::error::AppError,
        Extraction,
        Job,
        JobLease,
        ClaimStatus,
        Claim,
        ClaimDetail,
        ExportSnapshot,
        Settings,
        AppInfo,
        CsvExport,
        WorkspaceKind,
        Workspace,
        WorkspaceInput,
        CategoryKind,
        Category,
        CategoryInput,
        AccountKind,
        LoanDirection,
        Account,
        AccountInput,
        TransactionKind,
        PaymentMethod,
        TransactionSource,
        Transaction,
        TransactionInput,
        RecordExpenseInput,
        TransactionFilter,
        TransactionPage,
        Budget,
        BudgetInput,
        BudgetStatus,
        BudgetProgress,
        BillKind,
        Frequency,
        Bill,
        BillInput,
        OccurrenceStatus,
        BillOccurrence,
        BillDetail,
        BillPaymentInput,
        CategoryTotal,
        DailyTotal,
        MonthlyReport,
        CurrencyAmount,
        Overview,
        ReminderKind,
        Reminder,
        SuggestionStatus,
        TransactionSuggestion,
        QuickAddDraft
    );
    let path =
        std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../src/bindings/generated/index.ts");
    std::fs::write(path, output)?;
    Ok(())
}
